// Build-time replacement for the old server-side fs.readdir in app/hom/page.tsx.
// Scans public/thumbs for hom<N>.jpeg files and writes a sorted manifest that
// the SPA imports directly, so no server filesystem access is needed at runtime.
import { readdir, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const thumbsDir = path.join(root, "public", "thumbs");
const outFile = path.join(root, "src", "content", "generated", "homManifest.ts");

async function main() {
  let files = [];
  try {
    files = await readdir(thumbsDir);
  } catch {
    console.warn("[generate-hom] public/thumbs not found; writing empty manifest");
  }

  const images = files
    .filter((file) => /^hom\d+\.jpeg$/.test(file))
    .map((file) => file.replace(".jpeg", ""))
    .sort((a, b) => parseInt(a.replace("hom", ""), 10) - parseInt(b.replace("hom", ""), 10));

  const contents = `// AUTO-GENERATED by scripts/generate-hom-manifest.mjs — do not edit by hand.
export const homImages: string[] = ${JSON.stringify(images, null, 2)};
`;

  await mkdir(path.dirname(outFile), { recursive: true });
  await writeFile(outFile, contents, "utf8");
  console.log(`[generate-hom] wrote ${images.length} images -> src/content/generated/homManifest.ts`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
